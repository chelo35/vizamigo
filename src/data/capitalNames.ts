/** Turkish names that differ from what geoData stores (geoData keeps a few English forms). */
const TR_FIX: Record<string, string> = {
  US: 'Washington', MX: 'Meksiko', PA: 'Panama', GT: 'Guatemala', CO: 'Bogota', CR: 'San José', PY: 'Asunción', BO: 'La Paz ve Sucre'
};

const IDX: Record<string, number> = { en: 0, de: 1, es: 2, ru: 3 };

/** Capital in the page language; `trName` is geoData.capital (Turkish). */
export function capitalName(code: string, lang: string, trName = ''): string {
  if (lang === 'tr') return TR_FIX[code] || trName;
  const q = C[code];
  if (!q) return trName;
  return q[IDX[lang] ?? 0] || q[0];
}

/** Replace Turkish capital names inside a longer text (e.g. itinerary stop names). */
export function localizeCapitalIn(text: string, code: string, lang: string, trName: string): string {
  if (lang === 'tr' || !trName || !text) return text;
  const to = capitalName(code, lang, trName);
  return to === trName ? text : text.split(trName).join(to);
}
